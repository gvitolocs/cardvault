#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');
const { Pool } = require('pg');
const {
  compact,
  supabasePredictedNameTokens,
  supabaseRestPredictedNameTokens,
} = require('../api/marketplace-autocomplete');

const ROOT_DIR = path.resolve(__dirname, '..');
const OUTPUT_PATH = path.join(ROOT_DIR, 'lib/constants/first_char_token_suggestions.dart');
const DEFAULT_CHARACTERS = 'abcdefghijklmnopqrstuvwxyz0123456789'.split('');
const SPECIAL_START_QUERY = `
  select distinct left(compact_name, 1) as start
  from public.marketplace_card_name_tokens
  where language = $1
    and compact_name <> ''
    and left(compact_name, 1) !~ '^[a-z0-9]$'
  order by start
`;

function cleanEnvValue(value) {
  const trimmed = String(value || '').trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1).replace(/\\n/g, '\n');
  }
  return trimmed;
}

function loadLocalEnv() {
  const envPath = path.join(ROOT_DIR, '.env.local');
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const stripped = line.trim();
    if (!stripped || stripped.startsWith('#') || !stripped.includes('=')) continue;
    const separator = stripped.indexOf('=');
    const key = stripped.slice(0, separator).replace(/^export\s+/, '').trim();
    if (!key || process.env[key]) continue;
    process.env[key] = cleanEnvValue(stripped.slice(separator + 1));
  }
}

function createPool() {
  const connectionString =
    process.env.SUPABASE_NAME_INDEX_DATABASE_URL ||
    process.env.SUPABASE_DB_POOLER_URL ||
    process.env.SUPABASE_DB_URL;
  if (!connectionString) {
    throw new Error('SUPABASE_NAME_INDEX_DATABASE_URL or SUPABASE_DB_URL is required.');
  }
  const sslVerify = process.env.SUPABASE_NAME_INDEX_DATABASE_SSL_VERIFY === '1';
  const sanitizedConnectionString = sslVerify
    ? connectionString
    : connectionString.replace(/([?&])sslmode=[^&]+&?/i, (match, prefix) =>
        prefix === '?' && match.endsWith('&') ? '?' : prefix === '?' ? '' : '',
      ).replace(/[?&]$/, '');
  return new Pool({
    connectionString: sanitizedConnectionString,
    max: 2,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
    ssl: { rejectUnauthorized: sslVerify },
  });
}

function escapeDartString(value) {
  return String(value || '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'");
}

function renderDart(entries) {
  const generatedAt = new Date().toISOString();
  const lines = [
    '// Generated by scripts/generate-first-char-token-cache.js. Do not edit by hand.',
    '',
    "class FirstCharTokenSuggestion {",
    '  const FirstCharTokenSuggestion({',
    '    required this.display,',
    '    required this.normalized,',
    '    required this.confidence,',
    '    required this.cardCount,',
    '    required this.language,',
    '  });',
    '',
    '  final String display;',
    '  final String normalized;',
    '  final double confidence;',
    '  final int cardCount;',
    '  final String language;',
    '}',
    '',
    `const String firstCharTokenSuggestionsGeneratedAt = '${generatedAt}';`,
    '',
    'const Map<String, FirstCharTokenSuggestion> firstCharTokenSuggestions = {',
  ];
  for (const entry of entries) {
    lines.push(
      `  '${escapeDartString(entry.character)}': FirstCharTokenSuggestion(` +
        `display: '${escapeDartString(entry.display)}', ` +
        `normalized: '${escapeDartString(entry.normalized)}', ` +
        `confidence: ${entry.confidence.toFixed(6)}, ` +
        `cardCount: ${entry.cardCount}, ` +
        `language: '${escapeDartString(entry.language)}'),`,
    );
  }
  lines.push('};', '');
  return lines.join('\n');
}

async function usefulFirstCharacters(pool, language) {
  const starts = new Set(DEFAULT_CHARACTERS);
  if (!pool) {
    return [...starts].sort((left, right) => left.localeCompare(right));
  }
  const result = await pool.query(SPECIAL_START_QUERY, [language]);
  for (const row of result.rows) {
    const start = String(row.start || '').trim();
    if (start) starts.add(start);
  }
  return [...starts].sort((left, right) => left.localeCompare(right));
}

async function generate() {
  loadLocalEnv();
  let pool = null;
  try {
    pool = createPool();
    await pool.query('select 1');
  } catch {
    await pool?.end().catch(() => {});
    pool = null;
  }
  try {
    const language = 'en';
    const characters = await usefulFirstCharacters(pool, language);
    const entries = [];
    for (const character of characters) {
      const tokens = pool
        ? await supabasePredictedNameTokens(
            character,
            language,
            1,
            (sql, values) => pool.query(sql, values),
          )
        : await supabaseRestPredictedNameTokens(character, language, 1);
      const token = tokens[0];
      if (!token) continue;
      entries.push({
        character: compact(character).slice(0, 1) || character,
        display: token.display_token || token.display || '',
        normalized: token.normalized_token || token.normalized || '',
        confidence: Number(token.confidence || 0),
        cardCount: Number(token.card_count || token.ids_count || 0),
        language: token.language || language,
      });
    }
    const byCharacter = new Map(entries.map((entry) => [entry.character, entry]));
    const sortedEntries = [...byCharacter.values()]
      .filter((entry) => entry.character && entry.display && entry.normalized)
      .sort((left, right) => left.character.localeCompare(right.character));
    fs.writeFileSync(OUTPUT_PATH, renderDart(sortedEntries));
    const summary = {
      output: path.relative(ROOT_DIR, OUTPUT_PATH),
      language,
      transport: pool ? 'postgres' : 'rest',
      entries: sortedEntries.length,
      p: byCharacter.get('p') || null,
    };
    console.log(JSON.stringify(summary, null, 2));
    if (byCharacter.get('p')?.display !== 'Pikachu') {
      throw new Error('Expected first-character p suggestion to be Pikachu.');
    }
  } finally {
    await pool?.end().catch(() => {});
  }
}

if (require.main === module) {
  generate().catch((error) => {
    console.error(error.message || error);
    process.exitCode = 1;
  });
}
